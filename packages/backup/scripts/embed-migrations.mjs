import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const packageDirectory = dirname(dirname(fileURLToPath(import.meta.url)));
const migrationsDirectory = join(packageDirectory, "..", "db", "migrations");
const names = (await readdir(migrationsDirectory)).filter((name) => name.endsWith(".sql")).sort();
const migrations = [];
for (const name of names) {
  const sql = await readFile(join(migrationsDirectory, name), "utf8");
  migrations.push({ name, sql, sha256: createHash("sha256").update(sql).digest("hex") });
}
const contract = { version: 1, migrations };
const json = `${JSON.stringify(contract, null, 2)}\n`;
await writeFile(join(packageDirectory, "src", "schema-contract.json"), json);
await writeFile(
  join(packageDirectory, "src", "migrations.ts"),
  `// Generated by packages/backup/scripts/embed-migrations.mjs. Do not edit.\n` +
    `import contract from "./schema-contract.json";\n\n` +
    `export const EMBEDDED_SCHEMA_CONTRACT = contract;\n` +
    `export const EMBEDDED_MIGRATIONS = contract.migrations;\n`,
);
